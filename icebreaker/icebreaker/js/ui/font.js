// Font cache for different colors
const FONT_CANVAS_CACHE = {};

function getCharCanvas(char, color) {
  const upperChar = char.toUpperCase();
  const key = `${upperChar}_${color}`;
  if (FONT_CANVAS_CACHE[key]) return FONT_CANVAS_CACHE[key];

  const pattern = FONT_DATA[upperChar] || FONT_DATA[' '];
  const canvas = document.createElement('canvas');
  canvas.width = 8;
  canvas.height = 8;
  const ctx = canvas.getContext('2d');
  ctx.fillStyle = color;

  for (let y = 0; y < 8; y++) {
    const row = pattern[y] || '........';
    for (let x = 0; x < 8; x++) {
      if (row[x] === '1') {
        ctx.fillRect(x, y, 1, 1);
      }
    }
  }

  FONT_CANVAS_CACHE[key] = canvas;
  return canvas;
}

export function drawPixelText(ctx, text, startX, startY, color = C.WHITE, spacing = 8) {
  const str = String(text);
  for (let i = 0; i < str.length; i++) {
    const char = str[i];
    const charCanvas = getCharCanvas(char, color);
    ctx.drawImage(charCanvas, Math.floor(startX + i * spacing), Math.floor(startY));
  }
}
