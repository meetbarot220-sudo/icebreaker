// Conveyor / Slippery Moving Ice (16x8)
export function createConveyorIceCanvas(dir, baseColor, arrowColor) {
  const canvas = document.createElement('canvas');
  canvas.width = 16;
  canvas.height = 8;
  const ctx = canvas.getContext('2d');
  
  ctx.fillStyle = baseColor;
  ctx.fillRect(0, 0, 16, 8);
  
  ctx.fillStyle = arrowColor;
  if (dir < 0) {
    // Arrow pointing Left: < <
    ctx.fillRect(4, 2, 1, 4);
    ctx.fillRect(5, 3, 1, 2);
    ctx.fillRect(6, 4, 1, 1);
    ctx.fillRect(12, 2, 1, 4);
    ctx.fillRect(13, 3, 1, 2);
    ctx.fillRect(14, 4, 1, 1);
  } else {
    // Arrow pointing Right: > >
    ctx.fillRect(6, 2, 1, 4);
    ctx.fillRect(5, 3, 1, 2);
    ctx.fillRect(4, 4, 1, 1);
    ctx.fillRect(14, 2, 1, 4);
    ctx.fillRect(13, 3, 1, 2);
    ctx.fillRect(12, 4, 1, 1);
  }
  return canvas;
}

