// Helper to convert ascii matrix into canvas ImageData
// '.' = transparent
// Characters map to color table
export function createPixelCanvas(width, height, artString, colorMap) {
  const canvas = document.createElement('canvas');
  canvas.width = width;
  canvas.height = height;
  const ctx = canvas.getContext('2d');
  const imgData = ctx.createImageData(width, height);
  const data = imgData.data;

  // Clean lines
  const lines = artString.trim().split('\n').map(l => l.trim());
  
  for (let y = 0; y < height; y++) {
    const line = lines[y] || '';
    for (let x = 0; x < width; x++) {
      const char = line[x] || '.';
      if (char !== '.' && colorMap[char]) {
        const hex = colorMap[char];
        const r = parseInt(hex.slice(1, 3), 16);
        const g = parseInt(hex.slice(3, 5), 16);
        const b = parseInt(hex.slice(5, 7), 16);
        const idx = (y * width + x) * 4;
        data[idx] = r;
        data[idx + 1] = g;
        data[idx + 2] = b;
        data[idx + 3] = 255;
      }
    }
  }

  ctx.putImageData(imgData, 0, 0);
  return canvas;
}

