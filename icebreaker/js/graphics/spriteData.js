// Normal Breakable Ice Block (16x8)
export function createBreakableIceCanvas(baseColor, highlightColor, shadowColor) {
  const canvas = document.createElement('canvas');
  canvas.width = 16;
  canvas.height = 8;
  const ctx = canvas.getContext('2d');
  
  // Fill base
  ctx.fillStyle = baseColor;
  ctx.fillRect(0, 0, 16, 8);
  
  // Top highlight line
  ctx.fillStyle = highlightColor;
  ctx.fillRect(0, 0, 16, 1);
  ctx.fillRect(0, 1, 1, 6);
  
  // Bottom shadow
  ctx.fillStyle = shadowColor;
  ctx.fillRect(0, 7, 16, 1);
  ctx.fillRect(15, 1, 1, 6);
  
  // Inner brick / crystal fracture
  ctx.fillStyle = shadowColor;
  ctx.fillRect(8, 1, 1, 6); // Divider
  ctx.fillRect(3, 4, 3, 1);
  ctx.fillRect(11, 3, 3, 1);
  
  // Inner glint
  ctx.fillStyle = highlightColor;
  ctx.fillRect(1, 1, 2, 1);
  ctx.fillRect(9, 1, 2, 1);

  return canvas;
}

